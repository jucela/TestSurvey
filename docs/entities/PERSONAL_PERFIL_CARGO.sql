	"TELEFONO"	VARCHAR(100),
	"ESTADOCIVIL"	CHAR(1),
	"SEXO"	CHAR(1),
	CONSTRAINT "PK_PERSONAL" PRIMARY KEY("DNI"),
	CONSTRAINT "FK_PERSONAL_PERFIL" FOREIGN KEY("PERFIL") REFERENCES "PERFIL"("CODPERFIL"),
	CONSTRAINT "FK_PERSONAL_CARGO" FOREIGN KEY("CARGO") REFERENCES "CARGO"("CARGO")
