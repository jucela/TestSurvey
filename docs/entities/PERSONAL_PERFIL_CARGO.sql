CREATE TABLE IF NOT EXISTS "PERFIL" (
	"CODPERFIL"	CHAR(2) NOT NULL,
	"NOMPERFIL"	VARCHAR(50) NOT NULL UNIQUE,
	CONSTRAINT "PK_PERFIL" PRIMARY KEY("CODPERFIL")
);
CREATE TABLE IF NOT EXISTS "CARGO" (
	"CARGO"	CHAR(2) NOT NULL,
	"NOMCARGO"	VARCHAR(50),
	"ABRCARGO"	VARCHAR(10),
	CONSTRAINT "PK_CARGO" PRIMARY KEY("CARGO")
);
